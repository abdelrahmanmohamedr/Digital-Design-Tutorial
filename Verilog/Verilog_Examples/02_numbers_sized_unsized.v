// the format

[size]'[type] [Value];

//sized numbers

3'b010;         //3-bit binary number
7'd10           //7-bit decimal number
4'hA            //4-bit hexa number
32'hABCD_1234   //32-bit hexa number "can use underscore to make the number readable"

//unsized numbers

10               //32-bit decimal number "default"
'hAB             //32-bit hexa number
